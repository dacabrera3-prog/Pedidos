CREATE TABLE productos (
    nombre VARCHAR(150) PRIMARY KEY,
    descripcion VARCHAR(1000) NOT NULL,
    stock INTEGER NOT NULL CHECK (stock >= 0)
);

CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_pedido VARCHAR(32) NOT NULL,
    cliente VARCHAR(200) NOT NULL,
    nombre_producto VARCHAR(150) NOT NULL REFERENCES productos(nombre),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    estado VARCHAR(20) NOT NULL,
    codigo_verificacion VARCHAR(6) NOT NULL
);

CREATE INDEX idx_pedidos_codigo_pedido ON pedidos(codigo_pedido);
CREATE INDEX idx_pedidos_cliente_estado ON pedidos(cliente, estado);
